"""Pure-Python FDO91 compiler: the same bytes AOL's own compiler (Ada32.dll) produces.

Ada writes every atom in "full" style: [prefix] proto atom length args, where
  - a protocol number >= 32 gets a prefix byte 0xE0 | ((proto & 0x60) >> 2);
  - the length is one byte, or 0x80|hi, lo for 128+ bytes of args;
  - args are concatenated with no separators:
      12x            one byte
      123            big-endian, as few bytes as it needs (1-4); above 2^31-1 it saturates
      32-221 / 1-0-24836   a global id = (type<<16|id) or (type<<24|sub<<16|id), as a number
      "text"         Latin-1 bytes; escapes \\r \\t \\n \\\\ \\" \\xNN
      word           a per-atom enum value (atom_args.json, learned from Ada itself), an atom
                     name (2 bytes: proto, atom) or a variable letter A.. (one byte, 0..)
      a | b | 4      the OR of its terms
      nested atoms   (act_* actions) the compiled bytes of that atom stream
    the_unknown <p, a, bytes...> is an atom given by raw protocol/atom numbers.

atom_args.json is regenerated by tools/learn_fdo_args.py, which compiles every client form
with the real Ada compiler and learns the enum values and fixed number widths from it.
"""
import json
from pathlib import Path

from . import codec
from .fdoparse import Atom, ParseError, Tok, parse, unescape

_DATA = json.loads((Path(__file__).parent / "atom_args.json").read_text())
WORDS: dict[str, dict[tuple[int, str], bytes]] = {
    atom: {(int(k.split(":", 1)[0]), k.split(":", 1)[1]): bytes.fromhex(v) for k, v in d.items()}
    for atom, d in _DATA["words"].items()}
NUM_WIDTH = {(k.rsplit(":", 1)[0], int(k.rsplit(":", 1)[1])): w for k, w in _DATA["num_width"].items()}
FLAGS = {name: v.get("flags") for name, v in json.loads((Path(__file__).parent / "atoms.json").read_text()).items()}
VARS = {c: i for i, c in enumerate("ABCDEFGHIJKLMNOPQRSTUVWXYZ")}
TOKEN_ARG = 9        # atom flag: a token string, then data -- the token is exactly 2 bytes


def _shared_words():
    """Words an atom hasn't been seen with, borrowed from atoms of the same kind (e.g. the
    object types man_start_object knows are the same for man_start_sibling) when every atom
    of that kind that knows the word agrees on its value."""
    seen: dict[tuple, set] = {}
    for atom, table in WORDS.items():
        for (_, w), v in table.items():
            seen.setdefault((FLAGS.get(atom), w), set()).add(v)
    return {key: next(iter(vals)) for key, vals in seen.items() if len(vals) == 1}


SHARED = _shared_words()
STREAM_ARG = 6      # atom flag: the argument is a nested atom stream
ATOM_REF = (12, 18)  # atom flags whose word arguments name another atom
VAR_ARG = (15, 16, 17)


class CompileError(Exception):
    pass


def number(text, width=None) -> bytes:
    v = int(text)
    if v > 0x7FFFFFFF:
        v = 0x7FFFFFFF
    if v < 0:
        v &= 0xFFFFFFFF
    return v.to_bytes(width or max(1, (v.bit_length() + 7) // 8), "big")


def gid(text: str) -> bytes:
    p = [int(x) for x in text.split("-")]
    return number(p[0] << 16 | p[1] if len(p) == 2 else p[0] << 24 | p[1] << 16 | p[2])


def word(atom: str, pos: int, w: str) -> bytes:
    table = WORDS.get(atom, {})
    if (pos, w) in table:
        return table[(pos, w)]
    for (_, ww), v in table.items():
        if ww == w:
            return v
    flags = FLAGS.get(atom)
    if flags in ATOM_REF and w in codec.BY_NAME:
        return bytes(codec.BY_NAME[w])
    if flags in VAR_ARG and w in VARS:
        return bytes([VARS[w]])
    if (flags, w) in SHARED:
        return SHARED[(flags, w)]
    raise CompileError(f"{atom}: unknown word {w!r}")


def arg_bytes(atom: str, pos: int, toks: list[Tok]) -> bytes:
    if not toks:
        return b""
    if len(toks) == 1:
        k, t = toks[0].kind, toks[0].text
        if k == "hex":
            return bytes([int(t[:-1], 16)])
        if k == "num":
            return number(t, NUM_WIDTH.get((atom, pos)))
        if k == "gid":
            return gid(t)
        if k == "str":
            return unescape(t[1:-1])
        if k == "raw":
            return t.encode("latin1", "replace")
        if k == "word":
            return word(atom, pos, t)
    if any(t.text == "|" for t in toks):
        vals = [word(atom, pos, t.text) if t.kind == "word" else number(t.text) for t in toks if t.kind != "punct"]
        x = 0
        for v in vals:
            x |= int.from_bytes(v, "big")
        return x.to_bytes(max(len(v) for v in vals), "big")
    raise CompileError(f"{atom}: can't encode argument {' '.join(t.text for t in toks)!r}")


def atom_bytes(proto: int, num: int, args: bytes) -> bytes:
    head = bytes([0xE0 | ((proto & 0x60) >> 2)]) if proto >= 32 else b""
    n = len(args)
    # 2-byte lengths are 0x8000|n kept to 16 bits, as Ada writes them (wraps past 32K)
    length = bytes([n]) if n < 0x80 else ((0x8000 | n) & 0xFFFF).to_bytes(2, "big")
    return head + bytes([proto & 0x1F, num]) + length + args


def compile_atoms(atoms: list[Atom]) -> bytes:
    out = bytearray()
    for a in atoms:
        if a.name == "the_unknown":
            vals = [arg_bytes(a.name, i, t) for i, t in enumerate(a.args)]
            out += atom_bytes(int.from_bytes(vals[0], "big"), int.from_bytes(vals[1], "big"), b"".join(vals[2:]))
            continue
        if a.name not in codec.BY_NAME:
            raise CompileError(f"unknown atom {a.name!r}")
        proto, num = codec.BY_NAME[a.name]
        if FLAGS.get(a.name) == STREAM_ARG and a.args and a.args[0] and a.args[0][0].kind == "word":
            from .fdoparse import parse_tokens_as_stream
            args = b"".join(compile_atoms(parse_tokens_as_stream(t)) for t in a.args)
        else:
            parts = [arg_bytes(a.name, i, t) for i, t in enumerate(a.args)]
            if FLAGS.get(a.name) == TOKEN_ARG and len(parts) > 1:
                if len(parts[0]) < 2:
                    raise CompileError(f"{a.name}: token must be 2 characters")
                parts[0] = parts[0][:2]
            args = b"".join(parts)
        out += atom_bytes(proto, num, args)
    return bytes(out)


def compile_source(source: str) -> bytes:
    try:
        return compile_atoms(parse(source))
    except ParseError as e:
        raise CompileError(str(e)) from None
